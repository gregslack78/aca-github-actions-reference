from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
PACKAGE = BASE / "aca-reference" if (BASE / "aca-reference").is_dir() else BASE


def render(name):
    text = (PACKAGE / "samples" / ".github" / "workflows" / name).read_text(encoding="utf-8")
    defaults = "defaults:\n  run:\n    shell: bash\n    working-directory: samples\n"
    text = text.replace("permissions:", defaults + "permissions:", 1)
    if name == "ci.yml":
        text = text.replace(
            "on:\n  pull_request:",
            "on:\n  push:\n    branches: [main]\n  pull_request:",
            1,
        )
        text = text.replace(
            "group: pr-${{ github.event.pull_request.number }}",
            "group: ci-${{ github.event.pull_request.number || github.ref }}",
        )
        text = text.replace(
            "      - name: Test hello world",
            "      - name: Test deployment automation\n"
            "        working-directory: .\n"
            "        run: python3 -m unittest discover -s _authoring/tests -v\n"
            "      - name: Test hello world",
        )
    else:
        text = text.replace(
            "if: github.ref == 'refs/heads/main'",
            "if: github.ref == 'refs/heads/main' && vars.DEPLOYMENT_ENABLED == 'true'",
            1,
        )
        text = text.replace("path: release.json", "path: samples/release.json")
    return "# Generated by _authoring/render_workflows.py; edit samples/.github/workflows instead.\n" + text


if __name__ == "__main__":
    destination = PACKAGE / ".github" / "workflows"
    destination.mkdir(parents=True, exist_ok=True)
    for name in ("ci.yml", "release.yml", "rollback.yml"):
        (destination / name).write_text(render(name), encoding="utf-8", newline="\n")
